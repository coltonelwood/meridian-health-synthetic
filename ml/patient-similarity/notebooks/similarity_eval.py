# %% [markdown]
# ## 1. Same-Diagnosis Retrieval (Precision@K)

# %%
# For each query patient, what fraction of the top-K similar patients
# share at least one ICD-10 chapter (first letter) with the query?

# Results from eval run (2025-11-10):
precision_at_k = {
    "k=1": 0.892,
    "k=5": 0.834,
    "k=10": 0.791,
    "k=20": 0.743,
    "k=50": 0.682,
}

print("Same-Diagnosis Precision@K:")
for k, p in precision_at_k.items():
    print(f"  {k}: {p:.3f}")

# FINDING: 89% of top-1 matches share a major diagnosis category.
# Drops to 79% at k=10 which is still reasonable.
# These numbers look good but the metric is lenient - sharing
# the same ICD-10 chapter is a low bar (e.g., both have any
# circulatory condition).

# %%
# More granular: share same 3-character ICD-10 code?
precision_3char = {
    "k=1": 0.724,
    "k=5": 0.651,
    "k=10": 0.598,
    "k=20": 0.534,
}

print("\nSame 3-char ICD-10 Precision@K:")
for k, p in precision_3char.items():
    print(f"  {k}: {p:.3f}")

# FINDING: At the 3-char level, top-1 match shares a specific
# diagnosis 72% of the time. This is pretty good, considering
# patients can have many diagnoses and the model doesn't just
# match on diagnoses.

# %% [markdown]
# ## 2. Medication Overlap

# %%
# What fraction of medications overlap between query and matches?
# Using Jaccard similarity of medication sets

med_overlap = {
    "k=1": {"mean_jaccard": 0.412, "mean_overlap_count": 3.8},
    "k=5": {"mean_jaccard": 0.356, "mean_overlap_count": 3.2},
    "k=10": {"mean_jaccard": 0.318, "mean_overlap_count": 2.9},
}

print("Medication Overlap (Jaccard Similarity):")
for k, metrics in med_overlap.items():
    print(f"  {k}: Jaccard={metrics['mean_jaccard']:.3f}, "
          f"Avg shared meds={metrics['mean_overlap_count']:.1f}")

# FINDING: Average of 3.8 shared medications between a patient and
# their closest match. For context, patients average ~7 active meds,
# so ~54% overlap. This is encouraging.

