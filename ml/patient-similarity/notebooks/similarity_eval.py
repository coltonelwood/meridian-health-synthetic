#
# Interesting that PCA@128d doesn't improve much over PCA@64d.
# Suggests 64 dimensions capture most of the meaningful variance.

# %% [markdown]
# ## 4. Clinical Expert Review

# %%
# Dr. Martinez reviewed 50 random query-match pairs
# Each pair was rated on a 1-5 scale:
# 1 = completely different patients
# 2 = some similarities but not meaningful
# 3 = moderately similar, some shared conditions
# 4 = quite similar, would consider similar treatments
# 5 = very similar, nearly identical clinical profile

expert_ratings = {
    1: 3,   # 3 out of 50 rated 1
    2: 7,
    3: 14,
    4: 18,
    5: 8,
}

total = sum(expert_ratings.values())
mean_rating = sum(k * v for k, v in expert_ratings.items()) / total

print(f"\nExpert Review Results (n=50):")
print(f"Mean rating: {mean_rating:.2f} / 5.0")
for rating, count in sorted(expert_ratings.items()):
    print(f"  Rating {rating}: {count} ({count/total*100:.0f}%)")

# FINDING: Mean rating of 3.4/5.0 from clinical expert review.
# 52% of pairs rated 4 or 5 (clinically meaningful similarity).
# Only 6% rated 1 (completely different).
#
# Dr. Martinez's feedback:
# - Model does well matching by disease burden and complexity
# - Sometimes misses medication interactions/contraindications
# - Demographic similarity (age, sex) is appropriate
# - Would be useful for finding similar cases in tumor boards
# - Would NOT trust for treatment recommendations without review

